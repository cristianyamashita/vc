def build_stub(old: str, new: str) -> None:
    target = rel(old, new)
    new_slug = slug_of(new.split("#")[0])
    out = (
        STUB_TEMPLATE.replace("__GENERATED__", GENERATED)
        .replace("__TARGET_JS__", json.dumps(target))
        .replace("__TARGET_TEXT__", html.escape(new.split("#")[0].split("/")[-1]))
        .replace("__TARGET__", html.escape(target))
        .replace("__FAVICON__", icon_href(old, new_slug))
        .replace("__NAME__", html.escape(new.split("#")[0].split("/")[-1]))
    )
    (PAGE / old).write_text(out, encoding="utf-8")
    print(f"stub   {old} -> {new}")


def main() -> None:
    for hub in HUBS:
        if hub["file"] not in ENABLED_HUBS:
            continue
        build_hub(hub)
        for tab in hub["tabs"]:
            add_guard(tab["src"], hub["file"], tab["id"])
    for group, mapping in STUBS.items():
        if group not in ENABLED_STUBS:
            continue
        for old, new in mapping.items():
            if not (PAGE / new.split("#")[0]).exists():
                raise SystemExit(f"stub target missing: {new}")
            build_stub(old, new)
        for extra in OBSOLETE.get(group, []):
            path = PAGE / extra
            if path.exists():
                path.unlink()
                print(f"remove {extra}")


if __name__ == "__main__":
    main()
