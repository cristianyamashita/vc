def rel(from_file: str, to_path: str) -> str:
    """Relative URL from page/<from_file> to page/<to_path> (keeps #hash)."""
    path, _, frag = to_path.partition("#")
    out = os.path.relpath(PAGE / path, (PAGE / from_file).parent).replace(os.sep, "/")
    return out + ("#" + frag if frag else "")


def icon_href(from_file: str, slug: str) -> str:
    return rel(from_file, f"assets/icons/ico/{slug}.ico")


def slug_of(path: str) -> str:
    parts = path[:-5].split("/")
    return "-".join(parts)


