def build_hub(hub: dict) -> None:
    file = hub["file"]
    config = {
        "slug": hub["slug"],
        "title": hub["title"],
        "intro": hub["intro"],
        "fileTab": hub.get("fileTab"),
        "tabs": [
            {
                "id": t["id"],
                "src": rel(file, t["src"]),
                "icon": t["icon"],
                "label": t["label"],
                "desc": t["desc"],
                "unload": bool(t.get("unload")),
                "langKeys": t.get("langKeys", []),
                "themeKeys": t.get("themeKeys", []),
            }
            for t in hub["tabs"]
        ],
    }
    out = (
        HUB_TEMPLATE.replace("__GENERATED__", GENERATED)
        .replace("__FAVICON__", icon_href(file, hub["slug"]))
        .replace("__ICON_SVG__", rel(file, f"assets/icons/svg/{hub['slug']}.svg"))
        .replace("__FA__", rel(file, "assets/fontawesome/css/all.min.css"))
        .replace("__EMBED__", rel(file, "os/js/embed.js"))
        .replace("__TITLE__", html.escape(hub["title"]["en"]))
        .replace("__CONFIG__", json.dumps(config, ensure_ascii=False, indent=2).replace("\n", "\n      "))
        .replace("__TEXT__", json.dumps(HUB_I18N, ensure_ascii=False))
    )
    (PAGE / file).write_text(out, encoding="utf-8")
    print(f"hub    {file} ({len(hub['tabs'])} tabs)")


# --------------------------------------------------------------------------
# Guard injected into every page that lives inside a hub
# --------------------------------------------------------------------------

GUARD_RE = re.compile(r'\s*<script id="hub-guard">.*?</script>', re.S)


def guard_script(page_file: str, hub_file: str, tab_id: str) -> str:
    target = rel(page_file, hub_file)
    return (
        f'<script id="{GUARD_ID}">/* {GENERATED} */'
        "(function(){if(/[?&]hub=1(&|$)/.test(location.search)){document.documentElement.dataset.hub='1';return;}"
        f"var h=location.hash?':'+location.hash.slice(1):'';location.replace({json.dumps(target + '#' + tab_id)}+h);"
        "})();</script>"
    )


def add_guard(page_file: str, hub_file: str, tab_id: str) -> None:
    path = PAGE / page_file
    text = path.read_text(encoding="utf-8")
    text = GUARD_RE.sub("", text)
    m = re.search(r"<head[^>]*>", text, re.I)
    if not m:
        raise SystemExit(f"no <head> in {page_file}")
    text = text[: m.end()] + "\n  " + guard_script(page_file, hub_file, tab_id) + text[m.end():]
    path.write_text(text, encoding="utf-8")
    print(f"guard  {page_file} -> {hub_file}#{tab_id}")


